-- Supabase/PostgreSQL schema for cloud synchronization.
create extension if not exists "uuid-ossp";
create table if not exists app_users (
 id uuid primary key default uuid_generate_v4(), username varchar(100) unique not null,
 full_name varchar(150) not null, pin_hash text not null, role varchar(50) not null
 check(role in ('مدير النظام','محاسب','أمين مستودع')), is_active boolean default true,
 created_at timestamptz default now()
);
create table if not exists items (
 id bigint generated by default as identity primary key, name varchar(255) unique not null,
 category varchar(100) not null, unit varchar(50) not null, default_price numeric(10,2) default 0,
 opening_stock numeric(10,2) default 0, reorder_level numeric(10,2) default 0,
 is_active boolean default true, created_at timestamptz default now()
);
create table if not exists suppliers (
 id bigint generated by default as identity primary key, name varchar(255) unique not null,
 phone varchar(50), notes text
);
create table if not exists purchases (
 id uuid primary key default uuid_generate_v4(), purchase_date date not null default current_date,
 item_id bigint not null references items(id), supplier_id bigint references suppliers(id) on delete set null,
 quantity numeric(10,2) not null check(quantity>0), unit_price numeric(10,2) not null check(unit_price>=0),
 subtotal numeric(12,2) generated always as (round(quantity*unit_price,2)) stored,
 vat_amount numeric(12,2) generated always as (round(quantity*unit_price*0.15,2)) stored,
 total_with_vat numeric(12,2) generated always as (round(quantity*unit_price*1.15,2)) stored,
 payment_method varchar(100) not null, invoice_number varchar(100), notes text,
 created_by text, created_at timestamptz default now(), client_uuid uuid unique
);
create table if not exists stock_out (
 id uuid primary key default uuid_generate_v4(), out_date date not null default current_date,
 item_id bigint not null references items(id), movement_type varchar(100) not null,
 quantity numeric(10,2) not null check(quantity>0), unit_cost_snapshot numeric(10,2) not null default 0,
 total_cost numeric(12,2) generated always as (round(quantity*unit_cost_snapshot,2)) stored,
 recipient_or_reason text, created_by text, created_at timestamptz default now(), client_uuid uuid unique
);
create or replace view v_current_inventory as
select i.id,i.name,i.category,i.unit,i.opening_stock,
 coalesce(p.total_in,0) qty_in,coalesce(o.total_out,0) qty_out,
 i.opening_stock+coalesce(p.total_in,0)-coalesce(o.total_out,0) current_stock,
 case when coalesce(p.total_in,0)>0 then round(p.total_cost_in/p.total_in,2)
 else round(i.default_price*1.15,2) end avg_unit_cost,
 i.reorder_level,
 round((i.opening_stock+coalesce(p.total_in,0)-coalesce(o.total_out,0))*
 case when coalesce(p.total_in,0)>0 then p.total_cost_in/p.total_in else i.default_price*1.15 end,2) stock_value,
 case when i.opening_stock+coalesce(p.total_in,0)-coalesce(o.total_out,0)<=0 then 'نفد من المخزون'
 when i.opening_stock+coalesce(p.total_in,0)-coalesce(o.total_out,0)<=i.reorder_level then 'اطلب الآن' else 'متوفر' end stock_status
from items i left join (select item_id,sum(quantity) total_in,sum(total_with_vat) total_cost_in from purchases group by item_id) p on p.item_id=i.id
left join (select item_id,sum(quantity) total_out from stock_out group by item_id) o on o.item_id=i.id where i.is_active=true;

